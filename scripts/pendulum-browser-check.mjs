import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';

const base = process.env.BROWSER_CHECK_URL ?? 'http://127.0.0.1:4321';
const out = 'test-results/pendulum';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL ?? 'chrome', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/stem-lab/pendulum/`, { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('#apparatus')?.dataset.ready === 'true');
  const read = key => page.locator(`[data-value="${key}"]`).first().textContent();
  assert.equal(await read('time'), '0.00');
  assert.equal(await read('kinetic'), '0.00');
  assert.equal(await page.locator('#toggle').getAttribute('aria-pressed'), 'false');
  await page.screenshot({ path: `${out}/desktop.png`, fullPage: true });
  await page.locator('[data-camera="front"]').click();
  const box = await page.locator('#apparatus').boundingBox();
  const coordinates = await page.locator('#apparatus').evaluate(el => ({ x: Number(el.dataset.bobX), y: Number(el.dataset.bobY) }));
  await page.mouse.move(box.x + coordinates.x, box.y + coordinates.y);
  await page.mouse.down();
  assert.equal(await page.locator('#status').textContent(), '拉动摆球');
  await page.mouse.move(box.x + coordinates.x + 75, box.y + coordinates.y - 55, { steps: 12 });
  const draggedAngle = Number(await page.locator('#angle').inputValue());
  assert.ok(draggedAngle > 40 && draggedAngle <= 70, `drag changes angle: ${draggedAngle}`);
  await page.mouse.up();
  assert.equal(await page.locator('#toggle').getAttribute('aria-pressed'), 'true');
  await page.waitForFunction(() => Number(document.querySelector('[data-value="time"]').textContent) > .4);
  assert.ok(Number(await read('kinetic')) > 0);
  assert.ok((await page.locator('#kinetic-path').getAttribute('d')).includes('L'));
  await page.locator('#toggle').click();
  const paused = await read('time'); await page.waitForTimeout(200); assert.equal(await read('time'), paused);
  await page.locator('#step').click(); assert.ok(Number(await read('time')) > Number(paused));
  assert.equal(await page.locator('#toggle').getAttribute('aria-pressed'), 'false');
  await page.locator('#reset').click();
  assert.equal(await page.locator('#angle').inputValue(), '35');
  assert.equal(await page.locator('#mass').inputValue(), '1');
  await page.locator('#release').click();
  await page.waitForFunction(() => document.querySelector('#measured-period').textContent !== '—', undefined, { timeout: 15000 });
  assert.ok(Math.abs(Number(await page.locator('#measured-period').textContent()) - 2.52) < .02);
  assert.ok(Math.abs(Number(await read('mechanical')) - 2.66) < .02);
  await page.locator('#toggle').click();
  await page.locator('[data-mission="mass"]').click();
  assert.equal(await page.locator('#mass').inputValue(), '3');
  assert.equal(await page.locator('#compare').isChecked(), true);
  await page.getByRole('button', { name: '主摆更快', exact: true }).click();
  assert.equal(await page.locator('#answer-feedback').getAttribute('data-correct'), 'false');
  await page.getByRole('button', { name: '周期相同', exact: true }).click();
  assert.equal(await page.locator('#answer-feedback').getAttribute('data-correct'), 'true');
  await page.locator('[data-mission="length"]').click();
  assert.equal(await page.locator('#length').inputValue(), '2.4');
  assert.ok(Number.parseFloat(await page.locator('#theory-period').textContent()) > 3);
  await page.locator('#release').click(); await page.waitForTimeout(700); await page.locator('#toggle').click();
  await page.screenshot({ path: `${out}/comparison.png`, fullPage: true });
  await page.locator('[data-mission="energy"]').click();
  assert.equal(await page.locator('#forces').isChecked(), true);
  assert.equal(await page.locator('#slow').isChecked(), true);
  await page.locator('#reset').click();
  await page.locator('#gravity').selectOption('1.62');
  assert.ok(Number.parseFloat(await page.locator('#theory-period').textContent()) > 6);
  await page.locator('#damping').fill('0.3'); await page.locator('#damping').dispatchEvent('input');
  const initial = Number(await read('mechanical')); await page.locator('#release').click();
  await page.waitForFunction(() => Number(document.querySelector('[data-value="dissipated"]').textContent) > .02);
  await page.locator('#toggle').click(); assert.ok(Number(await read('mechanical')) < initial);
  await page.locator('#reset').click();
  await page.locator('#apparatus').focus(); await page.keyboard.press('Space');
  assert.equal(await page.locator('#toggle').getAttribute('aria-pressed'), 'true');
  await page.keyboard.press('Space'); assert.equal(await page.locator('#toggle').getAttribute('aria-pressed'), 'false');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 }); await page.waitForTimeout(150);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `no overflow at ${width}`);
    await page.screenshot({ path: `${out}/mobile-${width}.png`, fullPage: true });
  }
  const reduced = await browser.newPage({ reducedMotion: 'reduce' }); reduced.on('pageerror', e => errors.push(e.message));
  await reduced.goto(`${base}/stem-lab/pendulum/`, { waitUntil: 'networkidle' });
  assert.equal(await reduced.locator('#motion-note').isVisible(), true);
  assert.equal(await reduced.locator('#toggle').getAttribute('aria-pressed'), 'false');
  await reduced.locator('#step').click(); assert.ok(Number(await reduced.locator('[data-value="time"]').textContent()) > 0);
  await reduced.close();
  const fallback = await browser.newPage(); fallback.on('pageerror', e => errors.push(e.message));
  await fallback.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type, ...args) { return String(type).startsWith('webgl') ? null : original.call(this, type, ...args); };
  });
  await fallback.goto(`${base}/stem-lab/pendulum/`, { waitUntil: 'networkidle' });
  assert.equal(await fallback.locator('#apparatus').getAttribute('data-ready'), 'fallback');
  const bobX = await fallback.locator('#fallback-bob').getAttribute('cx');
  await fallback.locator('#forces').check(); await fallback.locator('#compare').check();
  await fallback.locator('#release').click(); await fallback.waitForTimeout(400); await fallback.locator('#toggle').click();
  assert.notEqual(await fallback.locator('#fallback-bob').getAttribute('cx'), bobX);
  assert.ok(Number(await fallback.locator('[data-value="kinetic"]').textContent()) > 0);
  assert.equal(await fallback.locator('#fallback-forces').getAttribute('visibility'), 'visible');
  assert.equal(await fallback.locator('#fallback-reference').getAttribute('visibility'), 'visible');
  assert.ok((await fallback.locator('#fallback-gravity').getAttribute('d')).includes('v'));
  assert.ok((await fallback.locator('#fallback-trail').getAttribute('d')).includes('L'));
  await fallback.screenshot({ path: `${out}/fallback.png`, fullPage: true }); await fallback.close();
  await page.goto(`${base}/stem-lab/buoyancy/`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('a[href="/stem-lab/pendulum/"]').count(), 1);
  await page.goto(`${base}/`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('[data-experiment-count]').first().innerText(), '12 个可探索实验');
  assert.equal(await page.locator('#apparatus').count(), 0); assert.deepEqual(errors, []);
  console.log('Pendulum browser checks passed: drag release, energy, period, pause, step, keyboard, missions, reference, gravity, damping, mobile, reduced motion, animated fallback and science home.');
} finally { await browser.close(); }
